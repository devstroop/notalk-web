import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const webRoot = join(scriptDir, '..')
const root = join(webRoot, 'templates')
const outPath = join(webRoot, 'src/lib/render/templates.bundled.ts')

function walk(dir, base) {
  const out = []
  for (const e of readdirSync(dir)) {
    const p = join(dir, e)
    const s = statSync(p)
    if (s.isDirectory()) out.push(...walk(p, join(base, e)))
    else if (e.endsWith('.html')) out.push(join(base, e))
  }
  return out
}

const files = walk(root, '').sort()
const entries = files.map(f => {
  const content = readFileSync(join(root, f), 'utf-8')
  // JSON stringify handles escaping
  return `  ${JSON.stringify(f)}: ${JSON.stringify(content)}`
})

const ts = `// AUTO-GENERATED by scripts/generate-templates.mjs — do not edit
// Generated at ${new Date().toISOString()} from templates/
export const bundledTemplates: Record<string, string> = {
${entries.join(',\n')}
}

export const bundledTemplateList = Object.keys(bundledTemplates)

export function hasBundled(path: string): boolean {
  return path in bundledTemplates
}
`

writeFileSync(outPath, ts, 'utf-8')
console.log(`Generated ${outPath} with ${files.length} templates (${Buffer.byteLength(ts)/1024|0} KiB)`)
for (const f of files) console.log(` - ${f}`)
